import { index, integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

// Bootstrap is restricted to OWNER_EMAIL. Once bound, authorization uses the
// stable authenticated ID; changing an email can never transfer ownership.
export const siteSettings = sqliteTable("site_settings", {
  key: text("key").primaryKey(),
  userId: text("user_id").notNull(),
  email: text("email").notNull(),
  createdAt: text("created_at").notNull(),
});

export const adminGrants = sqliteTable("admin_grants", {
  email: text("email").primaryKey(),
  userId: text("user_id").unique(),
  createdAt: text("created_at").notNull(),
});

// Current match and its archive are saved together in one atomic revision.
// The API enforces a 1.5 MiB UTF-8 limit, below D1's row size limit.
export const sharedState = sqliteTable("shared_state", {
  id: integer("id").primaryKey(),
  payload: text("payload").notNull(),
  revision: integer("revision").notNull(),
  updatedBy: text("updated_by").notNull(),
  updatedAt: text("updated_at").notNull(),
  mutationId: text("mutation_id").notNull().default("legacy"),
});

// Archive changes are generated by the API in the same transaction as state.
// Clients can read these rows as administrators but cannot submit audit rows.
export const recordAudit = sqliteTable("record_audit", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  stateRevision: integer("state_revision").notNull(),
  recordId: text("record_id").notNull(),
  actorId: text("actor_id").notNull(),
  actorName: text("actor_name").notNull(),
  createdAt: text("created_at").notNull(),
  action: text("action").notNull(),
  reason: text("reason").notNull(),
  beforeRecord: text("before_record"),
  afterRecord: text("after_record"),
}, table => [index("record_audit_record_id_idx").on(table.recordId, table.id)]);
